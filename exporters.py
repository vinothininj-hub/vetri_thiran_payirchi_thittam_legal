import html, re
from io import BytesIO
from pathlib import Path
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt
from fpdf import FPDF

def sanitize_text(text): return text.replace("\x00", "").strip()
def terms_from_text(text):
    return [re.sub(r"^\d+[.)]\s+", "", l.strip()) for l in text.splitlines() if re.match(r"^\d+[.)]\s+", l.strip())]
def format_html_preview(text):
    out=[]
    for raw in sanitize_text(text).splitlines():
        line=raw.strip()
        if not line: out.append("<div class='spacer'></div>")
        elif re.match(r"^\d+[.)]\s+", line) or (len(line)<100 and line.isupper()): out.append(f"<h3>{html.escape(line)}</h3>")
        else: out.append(f"<p>{html.escape(line)}</p>")
    return "\n".join(out)

def format_docx(text, title, logo_bytes=None):
    document=Document(); section=document.sections[0]
    section.top_margin=section.bottom_margin=Inches(.7); section.left_margin=section.right_margin=Inches(.8)
    document.styles["Normal"].font.name="Times New Roman"; document.styles["Normal"].font.size=Pt(11)
    if logo_bytes: document.add_picture(BytesIO(logo_bytes), width=Inches(1.4))
    p=document.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.CENTER; r=p.add_run(title); r.bold=True; r.font.size=Pt(16)
    for raw in sanitize_text(text).splitlines():
        line=raw.strip(); p=document.add_paragraph()
        if not line: continue
        r=p.add_run(line)
        if re.match(r"^\d+[.)]\s+", line) or (len(line)<100 and line.isupper()): r.bold=True
    terms=terms_from_text(text)
    if terms:
        document.add_page_break(); document.add_heading("Terms Summary", level=1)
        table=document.add_table(rows=1, cols=2); table.style="Table Grid"; table.rows[0].cells[0].text="No."; table.rows[0].cells[1].text="Term"
        for i,t in enumerate(terms,1): cells=table.add_row().cells; cells[0].text=str(i); cells[1].text=t
    footer=section.footer.paragraphs[0]; footer.alignment=WD_ALIGN_PARAGRAPH.CENTER; footer.add_run("Generated by LegalEase — AI-assisted drafting tool")
    out=BytesIO(); document.save(out); return out.getvalue()

class BrandedPDF(FPDF):
    def __init__(self, logo_path=None): super().__init__(); self.logo_path=logo_path
    def header(self):
        if self.logo_path and Path(self.logo_path).exists(): self.image(self.logo_path, x=10, y=8, w=24); self.set_xy(38,12)
        self.set_font("Helvetica","B",10); self.cell(0,8,"LegalEase",new_x="LMARGIN",new_y="NEXT"); self.ln(5)
    def footer(self):
        self.set_y(-15); self.set_font("Helvetica","",8); self.cell(0,10,f"Page {self.page_no()} | AI-assisted draft",align="C")

def format_pdf(text, title, logo_bytes=None):
    logo_path=None
    if logo_bytes: logo_path="/tmp/legalease_logo.png"; Path(logo_path).write_bytes(logo_bytes)
    pdf=BrandedPDF(logo_path); pdf.set_auto_page_break(auto=True,margin=20); pdf.add_page(); pdf.set_title(title)
    pdf.set_font("Helvetica","B",16); pdf.multi_cell(0,10,title,align="C"); pdf.ln(4)
    for raw in sanitize_text(text).splitlines():
        line=raw.strip()
        if not line: pdf.ln(5); continue
        heading=bool(re.match(r"^\d+[.)]\s+",line)) or (len(line)<100 and line.isupper())
        pdf.set_font("Helvetica","B" if heading else "",11); pdf.multi_cell(0,6,line)
    result=pdf.output(); return bytes(result)
